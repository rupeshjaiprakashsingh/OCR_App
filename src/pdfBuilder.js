const fs = require('fs');
const path = require('path');
const readline = require('readline');
const {
  PDFDocument,
  StandardFonts,
  degrees
} = require('pdf-lib');

/**
 * Sanitizes text to WinAnsi (Latin-1) printable characters supported by StandardFonts.Helvetica
 */
function sanitizeWinAnsi(text) {
  if (!text) return '';
  return text
    .replace(/\uFB00/g, 'ff')
    .replace(/\uFB01/g, 'fi')
    .replace(/\uFB02/g, 'fl')
    .replace(/\uFB03/g, 'ffi')
    .replace(/\uFB04/g, 'ffl')
    .replace(/[\u2018\u2019\u201A\u201B]/g, "'")
    .replace(/[\u201C\u201D\u201E\u201F]/g, '"')
    .replace(/[\u2013\u2014\u2015]/g, '-')
    .replace(/\u2026/g, '...')
    .replace(/\u00A0/g, ' ')
    .replace(/[^\x20-\x7E\xA1-\xFF]/g, '');
}

/**
 * Escapes a string for use inside a literal PDF string (...)
 */
function escapePdfLiteralString(str) {
  let out = '';
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    if (ch === '\\') out += '\\\\';
    else if (ch === '(') out += '\\(';
    else if (ch === ')') out += '\\)';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\n') out += '\\n';
    else out += ch;
  }
  return out;
}

/**
 * Reads the JSONL file generated by WinOcrEngine.exe full
 */
async function readOcrJsonl(jsonlPath) {
  const pages = [];
  if (!fs.existsSync(jsonlPath)) return pages;

  const fileStream = fs.createReadStream(jsonlPath, { encoding: 'utf8' });
  const rl = readline.createInterface({
    input: fileStream,
    crlfDelay: Infinity
  });

  for await (const line of rl) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    try {
      const obj = JSON.parse(trimmed);
      pages[obj.pageIndex] = obj;
    } catch (_) {}
  }
  return pages;
}

/**
 * Writes updated OCR pages array back to JSONL cache
 */
async function writeOcrJsonl(jsonlPath, pages) {
  const lines = pages.map((p, idx) => JSON.stringify(p || { pageIndex: idx, lines: [] }));
  await fs.promises.writeFile(jsonlPath, lines.join('\n') + '\n', 'utf8');
}

/**
 * Builds default QC page states from OCR + pixel metrics
 */
function createDefaultPageStates(ocrPages, options = {}) {
  const autoDeleteBlanks = options.autoDeleteBlanks !== false;
  const autoCrop = options.autoCrop !== false;
  const autoRotate = options.autoRotate !== false;

  return ocrPages.map((p, idx) => {
    const isBlank = !!(p && p.isBlank);
    const detectedRotation = (p && p.detectedRotation) || 0;
    const defaultCrop = (p && p.cropBox) || { left: 1.5, top: 1.5, right: 1.5, bottom: 1.5 };
    const wordCount = p && typeof p.wordCount === 'number'
      ? p.wordCount
      : (p && Array.isArray(p.lines) ? p.lines.reduce((acc, l) => acc + ((l.words && l.words.length) || 0), 0) : 0);

    return {
      pageIndex: idx,
      pageNumber: idx + 1,
      isBlank,
      inkRatio: (p && p.inkRatio) || 0,
      hasDarkBorder: !!(p && p.hasDarkBorder),
      confidence: (p && p.confidence) || (isBlank ? 100 : 98.5),
      wordCount,
      deleted: autoDeleteBlanks && isBlank,
      rotation: autoRotate ? detectedRotation : 0,
      cropEnabled: autoCrop,
      cropBox: {
        left: Number(defaultCrop.left || 0),
        top: Number(defaultCrop.top || 0),
        right: Number(defaultCrop.right || 0),
        bottom: Number(defaultCrop.bottom || 0)
      }
    };
  });
}

/**
 * Embeds an invisible searchable OCR text layer (PDF 3 Tr mode) into the scanned PDF,
 * applies QC page deletions (blank removal), rotations, and margin cropping,
 * and sets the PDF Title and Author metadata.
 */
async function buildSearchablePdf({
  inputPdfPath,
  ocrJsonlPath,
  outputPdfPath,
  bookTitle,
  authorName,
  pageStates = null,
  autoDeleteBlanks = true,
  autoCrop = true,
  autoRotate = true,
  onProgress
}) {
  const ocrPages = await readOcrJsonl(ocrJsonlPath);
  const existingPdfBytes = await fs.promises.readFile(inputPdfPath);
  const pdfDoc = await PDFDocument.load(existingPdfBytes, {
    ignoreEncryption: true,
    updateMetadata: false
  });

  if (bookTitle) pdfDoc.setTitle(bookTitle);
  if (authorName) pdfDoc.setAuthor(authorName);
  pdfDoc.setSubject(`Searchable OCR Book - ${bookTitle || ''} by ${authorName || ''}`);
  pdfDoc.setCreator('24x7 Book Scanner QC & OCR Studio');
  pdfDoc.setProducer('24x7 Local Book OCR Engine (WinRT + pdf-lib)');

  const helveticaFont = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const pdfPages = pdfDoc.getPages();

  const resolvedStates =
    Array.isArray(pageStates) && pageStates.length === pdfPages.length
      ? pageStates
      : createDefaultPageStates(ocrPages, { autoDeleteBlanks, autoCrop, autoRotate });

  let totalWordsEmbedded = 0;
  let pagesWithText = 0;
  let deletedBlankCount = 0;
  let croppedPageCount = 0;
  let rotatedPageCount = 0;

  for (let i = 0; i < pdfPages.length; i++) {
    const pState = resolvedStates[i] || { deleted: false, rotation: 0, cropEnabled: false };
    if (pState.deleted) {
      deletedBlankCount++;
      continue;
    }

    const page = pdfPages[i];
    const ocrPage = ocrPages[i];
    const { width: pdfW, height: pdfH } = page.getSize();

    // 1. Apply Rotation if requested
    const rotDelta = ((pState.rotation || 0) % 360 + 360) % 360;
    if (rotDelta !== 0) {
      const currentRot = page.getRotation().angle || 0;
      page.setRotation(degrees((currentRot + rotDelta) % 360));
      rotatedPageCount++;
    }

    // 2. Apply Cropping (removes scanner borders / margins cleanly via PDF CropBox)
    if (pState.cropEnabled && pState.cropBox) {
      const lPct = Math.max(0, Math.min(35, Number(pState.cropBox.left) || 0));
      const tPct = Math.max(0, Math.min(35, Number(pState.cropBox.top) || 0));
      const rPct = Math.max(0, Math.min(35, Number(pState.cropBox.right) || 0));
      const bPct = Math.max(0, Math.min(35, Number(pState.cropBox.bottom) || 0));

      if (lPct > 0.1 || tPct > 0.1 || rPct > 0.1 || bPct > 0.1) {
        const cropX = pdfW * (lPct / 100.0);
        const cropY = pdfH * (bPct / 100.0);
        const cropW = Math.max(50, pdfW * (1.0 - (lPct + rPct) / 100.0));
        const cropH = Math.max(50, pdfH * (1.0 - (tPct + bPct) / 100.0));
        page.setCropBox(cropX, cropY, cropW, cropH);
        croppedPageCount++;
      }
    }

    // 3. Embed Invisible Searchable Text Layer (3 Tr)
    if (ocrPage && Array.isArray(ocrPage.lines) && ocrPage.lines.length > 0) {
      const imgW = ocrPage.imgWidth || pdfW;
      const imgH = ocrPage.imgHeight || pdfH;
      const scaleX = pdfW / imgW;
      const scaleY = pdfH / imgH;

      const fontKey = page.node.newFontDictionary('F_OCR', helveticaFont.ref);
      const fontKeyStr = fontKey.asString();

      const ops = [];
      ops.push('q');
      ops.push('3 Tr');

      let pageHasWords = false;

      for (const line of ocrPage.lines) {
        const words = Array.isArray(line.words) ? line.words : [];
        if (words.length === 0) continue;

        for (let wIdx = 0; wIdx < words.length; wIdx++) {
          const wObj = words[wIdx];
          const cleanWord = sanitizeWinAnsi(wObj.t);
          if (!cleanWord) continue;

          const textWithSpace = wIdx < words.length - 1 ? cleanWord + ' ' : cleanWord;

          const targetX = wObj.x * scaleX;
          const targetW = Math.max(1, wObj.w * scaleX);
          const targetH = Math.max(4, wObj.h * scaleY);
          const targetY = Math.max(0, pdfH - (wObj.y + wObj.h * 0.85) * scaleY);

          const fontSize = Math.max(4, Math.min(120, targetH));
          let measuredW = 0;
          try {
            measuredW = helveticaFont.widthOfTextAtSize(cleanWord, fontSize);
          } catch (_) {
            measuredW = cleanWord.length * fontSize * 0.5;
          }

          let horizScale = 100;
          if (measuredW > 0.5 && targetW > 0.5) {
            horizScale = Math.max(30, Math.min(300, (targetW / measuredW) * 100));
          }

          const escaped = escapePdfLiteralString(textWithSpace);
          ops.push(
            `BT ${fontKeyStr} ${fontSize.toFixed(1)} Tf ${horizScale.toFixed(1)} Tz ${targetX.toFixed(2)} ${targetY.toFixed(2)} Td (${escaped}) Tj ET`
          );

          totalWordsEmbedded++;
          pageHasWords = true;
        }
      }

      ops.push('Q');

      if (pageHasWords) {
        pagesWithText++;
        const streamContent = ops.join('\n');
        const contentStream = pdfDoc.context.flateStream(streamContent);
        const contentStreamRef = pdfDoc.context.register(contentStream);
        page.node.normalize();
        page.node.addContentStream(contentStreamRef);
      }
    }

    if (onProgress && (i % 25 === 0 || i === pdfPages.length - 1)) {
      onProgress(i + 1, pdfPages.length);
    }
  }

  // 4. Delete pages marked as blank / deleted (in reverse order so indices stay valid)
  for (let i = pdfPages.length - 1; i >= 0; i--) {
    const pState = resolvedStates[i];
    if (pState && pState.deleted && pdfDoc.getPageCount() > 1) {
      pdfDoc.removePage(i);
    }
  }

  const outDir = path.dirname(outputPdfPath);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const finalPdfBytes = await pdfDoc.save({ useObjectStreams: false });
  let actualSavedPath = outputPdfPath;
  try {
    await fs.promises.writeFile(actualSavedPath, finalPdfBytes);
  } catch (writeErr) {
    if (writeErr.code === 'EBUSY' || writeErr.code === 'EPERM' || writeErr.code === 'EACCES') {
      const ext = path.extname(outputPdfPath);
      const base = path.basename(outputPdfPath, ext);
      let suffix = 1;
      while (true) {
        const altPath = path.join(outDir, `${base} (QC-${suffix})${ext}`);
        try {
          await fs.promises.writeFile(altPath, finalPdfBytes);
          actualSavedPath = altPath;
          break;
        } catch (_) {
          suffix++;
          if (suffix > 20) throw writeErr;
        }
      }
    } else {
      throw writeErr;
    }
  }

  return {
    actualSavedPath,
    originalPageCount: pdfPages.length,
    finalPageCount: pdfDoc.getPageCount(),
    deletedBlankCount,
    croppedPageCount,
    rotatedPageCount,
    pagesWithText,
    totalWordsEmbedded,
    outputSizeBytes: finalPdfBytes.length,
    pageStates: resolvedStates
  };
}

module.exports = {
  buildSearchablePdf,
  readOcrJsonl,
  writeOcrJsonl,
  createDefaultPageStates,
  sanitizeWinAnsi
};
