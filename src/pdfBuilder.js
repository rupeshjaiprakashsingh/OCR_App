const fs = require('fs');
const path = require('path');
const readline = require('readline');
const {
  PDFDocument,
  StandardFonts,
  degrees
} = require('pdf-lib');

/**
 * Sanitizes text to WinAnsi (Latin-1) printable characters supported by StandardFonts.Helvetica
 */
function sanitizeWinAnsi(text) {
  if (!text) return '';
  return text
    .replace(/\uFB00/g, 'ff')
    .replace(/\uFB01/g, 'fi')
    .replace(/\uFB02/g, 'fl')
    .replace(/\uFB03/g, 'ffi')
    .replace(/\uFB04/g, 'ffl')
    .replace(/[\u2018\u2019\u201A\u201B]/g, "'")
    .replace(/[\u201C\u201D\u201E\u201F]/g, '"')
    .replace(/[\u2013\u2014\u2015]/g, '-')
    .replace(/\u2026/g, '...')
    .replace(/\u00A0/g, ' ')
    .replace(/[^\x20-\x7E\xA1-\xFF]/g, '');
}

/**
 * Escapes a string for use inside a literal PDF string (...)
 */
function escapePdfLiteralString(str) {
  let out = '';
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    if (ch === '\\') out += '\\\\';
    else if (ch === '(') out += '\\(';
    else if (ch === ')') out += '\\)';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\n') out += '\\n';
    else out += ch;
  }
  return out;
}

/**
 * Reads the JSONL file generated by WinOcrEngine.exe
 */
async function readOcrJsonl(jsonlPath) {
  const pages = [];
  if (!fs.existsSync(jsonlPath)) return pages;

  const fileStream = fs.createReadStream(jsonlPath, { encoding: 'utf8' });
  const rl = readline.createInterface({
    input: fileStream,
    crlfDelay: Infinity
  });

  for await (const line of rl) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    try {
      const obj = JSON.parse(trimmed);
      pages[obj.pageIndex] = obj;
    } catch (_) {}
  }
  return pages;
}

/**
 * Writes updated OCR pages array back to JSONL cache
 */
async function writeOcrJsonl(jsonlPath, pages) {
  const lines = pages.map((p, idx) => JSON.stringify(p || { pageIndex: idx, lines: [] }));
  await fs.promises.writeFile(jsonlPath, lines.join('\n') + '\n', 'utf8');
}

/**
 * Builds default QC page states from OCR + pixel metrics
 */
function createDefaultPageStates(ocrPages, options = {}) {
  const autoDeleteBlanks = options.autoDeleteBlanks !== false;
  const autoCrop = options.autoCrop !== false;
  const autoRotate = options.autoRotate !== false;

  return ocrPages.map((p, idx) => {
    const isBlank = !!(p && p.isBlank);
    const detectedRotation = (p && p.detectedRotation) || 0;
    const defaultCrop = (p && p.cropBox) || { left: 1.5, top: 1.5, right: 1.5, bottom: 1.5 };
    const wordCount = p && typeof p.wordCount === 'number'
      ? p.wordCount
      : (p && Array.isArray(p.lines) ? p.lines.reduce((acc, l) => acc + ((l.words && l.words.length) || 0), 0) : 0);

    return {
      pageIndex: idx,
      pageNumber: idx + 1,
      isBlank,
      inkRatio: (p && p.inkRatio) || 0,
      hasDarkBorder: !!(p && p.hasDarkBorder),
      detectedRotation,
      confidence: (p && p.confidence) || (isBlank ? 100 : 98.5),
      wordCount,
      deleted: autoDeleteBlanks && isBlank,
      rotation: autoRotate ? detectedRotation : 0,
      cropEnabled: autoCrop,
      cropBox: {
        left: Number(defaultCrop.left || 0),
        top: Number(defaultCrop.top || 0),
        right: Number(defaultCrop.right || 0),
        bottom: Number(defaultCrop.bottom || 0)
      }
    };
  });
}

function computeMedian(values) {
  if (!values || values.length === 0) return 0;
  const sorted = values.slice().sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)];
}

/**
 * Computes the uniform standard page size (stdW x stdH) across all pages in the book
 * so every page in the final PDF has the exact same dimensions and orientation.
 */
function computeUniformBookPageSize(pdfPages, resolvedStates) {
  const portraitWidths = [];
  const portraitHeights = [];
  let portraitVotes = 0;
  let landscapeVotes = 0;

  for (let i = 0; i < pdfPages.length; i++) {
    const st = resolvedStates[i];
    if (st && st.deleted) continue;
    const mb = pdfPages[i].getMediaBox();
    const w = mb.width || 595;
    const h = mb.height || 842;
    const rot = (((pdfPages[i].getRotation().angle || 0) + ((st && st.rotation) || 0)) % 360 + 360) % 360;
    const effW = rot === 90 || rot === 270 ? h : w;
    const effH = rot === 90 || rot === 270 ? w : h;

    if (effH >= effW) portraitVotes++;
    else landscapeVotes++;

    portraitWidths.push(Math.min(w, h));
    portraitHeights.push(Math.max(w, h));
  }

  const medShort = computeMedian(portraitWidths) || 595;
  const medLong = computeMedian(portraitHeights) || 842;

  // If >75% of the book is genuinely landscape slides, use landscape; otherwise standardize all pages to Portrait
  if (landscapeVotes > portraitVotes * 3) {
    return { stdW: Number(medLong.toFixed(2)), stdH: Number(medShort.toFixed(2)) };
  }
  return { stdW: Number(medShort.toFixed(2)), stdH: Number(medLong.toFixed(2)) };
}

/**
 * Embeds an invisible searchable OCR text layer (PDF 3 Tr mode) into the scanned PDF,
 * physically rotates pages (90/180/270 deg) inside the PDF content stream,
 * clips cropped scanner borders, and normalizes all pages to a uniform page size (stdW x stdH).
 */
async function buildSearchablePdf({
  inputPdfPath,
  ocrJsonlPath,
  outputPdfPath,
  bookTitle,
  authorName,
  pageStates = null,
  autoDeleteBlanks = true,
  autoCrop = true,
  autoRotate = true,
  onProgress
}) {
  const ocrPages = await readOcrJsonl(ocrJsonlPath);
  const existingPdfBytes = await fs.promises.readFile(inputPdfPath);
  const pdfDoc = await PDFDocument.load(existingPdfBytes, {
    ignoreEncryption: true,
    updateMetadata: false
  });

  if (bookTitle) pdfDoc.setTitle(bookTitle);
  if (authorName) pdfDoc.setAuthor(authorName);
  pdfDoc.setSubject(`Searchable OCR Book - ${bookTitle || ''} by ${authorName || ''}`);
  pdfDoc.setCreator('24x7 Book Scanner QC & OCR Studio');
  pdfDoc.setProducer('24x7 Local Book OCR Engine (WinRT + pdf-lib)');

  const helveticaFont = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const pdfPages = pdfDoc.getPages();

  const resolvedStates =
    Array.isArray(pageStates) && pageStates.length === pdfPages.length
      ? pageStates
      : createDefaultPageStates(ocrPages, { autoDeleteBlanks, autoCrop, autoRotate });

  const { stdW, stdH } = computeUniformBookPageSize(pdfPages, resolvedStates);

  let totalWordsEmbedded = 0;
  let pagesWithText = 0;
  let deletedBlankCount = 0;
  let croppedPageCount = 0;
  let rotatedPageCount = 0;

  for (let i = 0; i < pdfPages.length; i++) {
    const pState = resolvedStates[i] || { deleted: false, rotation: 0, cropEnabled: false };
    if (pState.deleted) {
      deletedBlankCount++;
      continue;
    }

    const page = pdfPages[i];
    const ocrPage = ocrPages[i];
    const mb = page.getMediaBox();
    const mbX = mb.x || 0;
    const mbY = mb.y || 0;
    const W = mb.width || stdW;
    const H = mb.height || stdH;

    const origRot = ((page.getRotation().angle || 0) % 360 + 360) % 360;
    const userRot = ((pState.rotation || 0) % 360 + 360) % 360;
    const rotDeg = (origRot + userRot) % 360;

    if (userRot !== 0 || (W > H && stdW < stdH)) {
      rotatedPageCount++;
    }

    // 1. Compute upright rotated dimensions (rw x rh) and 2D rotation matrix (r_a..r_f)
    let rw = W;
    let rh = H;
    let r_a = 1, r_b = 0, r_c = 0, r_d = 1, r_e = -mbX, r_f = -mbY;

    if (rotDeg === 90) {
      rw = H;
      rh = W;
      r_a = 0; r_b = -1; r_c = 1; r_d = 0; r_e = -mbY; r_f = W + mbX;
    } else if (rotDeg === 180) {
      rw = W;
      rh = H;
      r_a = -1; r_b = 0; r_c = 0; r_d = -1; r_e = W + mbX; r_f = H + mbY;
    } else if (rotDeg === 270) {
      rw = H;
      rh = W;
      r_a = 0; r_b = 1; r_c = -1; r_d = 0; r_e = H + mbY; r_f = -mbX;
    }

    // 2. Compute crop box in upright (rw x rh) coordinates
    let lPct = 0, tPct = 0, rPct = 0, bPct = 0;
    if (pState.cropEnabled && pState.cropBox) {
      lPct = Math.max(0, Math.min(35, Number(pState.cropBox.left) || 0));
      tPct = Math.max(0, Math.min(35, Number(pState.cropBox.top) || 0));
      rPct = Math.max(0, Math.min(35, Number(pState.cropBox.right) || 0));
      bPct = Math.max(0, Math.min(35, Number(pState.cropBox.bottom) || 0));
      if (lPct > 0.1 || tPct > 0.1 || rPct > 0.1 || bPct > 0.1) {
        croppedPageCount++;
      }
    }

    const cropX = rw * (lPct / 100.0);
    const cropY = rh * (bPct / 100.0);
    const cropW = Math.max(50, rw * (1.0 - (lPct + rPct) / 100.0));
    const cropH = Math.max(50, rh * (1.0 - (tPct + bPct) / 100.0));

    // 3. Map upright cropped region [cropX, cropY, cropW, cropH] onto uniform page [0, 0, stdW, stdH]
    const isWideOnPortrait = cropW > cropH * 1.05 && stdW < stdH;
    const padFactor = isWideOnPortrait ? 0.96 : 1.0;
    const s = Math.min((stdW * padFactor) / cropW, (stdH * padFactor) / cropH);
    const destX = (stdW - cropW * s) / 2.0;
    const destY = (stdH - cropH * s) / 2.0;
    const destW = cropW * s;
    const destH = cropH * s;

    const A = s * r_a;
    const B = s * r_b;
    const C = s * r_c;
    const D = s * r_d;
    const E = s * r_e + (destX - s * cropX);
    const F = s * r_f + (destY - s * cropY);

    page.node.normalize();

    // Prepend graphics state save, border-crop clipping rectangle, and physical rotation/normalization matrix
    const prefixOps = [
      'q',
      `${destX.toFixed(2)} ${destY.toFixed(2)} ${destW.toFixed(2)} ${destH.toFixed(2)} re W n`,
      `${A.toFixed(5)} ${B.toFixed(5)} ${C.toFixed(5)} ${D.toFixed(5)} ${E.toFixed(2)} ${F.toFixed(2)} cm`
    ].join('\n') + '\n';
    const prefixStream = pdfDoc.context.flateStream(prefixOps);
    const prefixRef = pdfDoc.context.register(prefixStream);
    const contentsArr = page.node.Contents();
    if (contentsArr && typeof contentsArr.insert === 'function') {
      contentsArr.insert(0, prefixRef);
    }

    // 4. Build suffix stream: restore graphics state ('Q') + embed Invisible Searchable Text Layer (3 Tr)
    const suffixOps = ['\nQ'];

    if (ocrPage && Array.isArray(ocrPage.lines) && ocrPage.lines.length > 0) {
      const ocrRot = ((ocrPage.detectedRotation || 0) % 360 + 360) % 360;
      const baseImgW = ocrPage.imgWidth || rw;
      const baseImgH = ocrPage.imgHeight || rh;
      // Map OCR coordinates (which are in ocrRot orientation) to current userRot orientation if operator rotated manually in QC
      const relRot = ((userRot - ocrRot) % 360 + 360) % 360;
      const effImgW = relRot === 90 || relRot === 270 ? baseImgH : baseImgW;
      const effImgH = relRot === 90 || relRot === 270 ? baseImgW : baseImgH;

      const scaleX = rw / effImgW;
      const scaleY = rh / effImgH;

      const fontKey = page.node.newFontDictionary('F_OCR', helveticaFont.ref);
      const fontKeyStr = fontKey.asString();

      suffixOps.push('q');
      suffixOps.push('3 Tr');

      let pageHasWords = false;

      for (const line of ocrPage.lines) {
        const words = Array.isArray(line.words) ? line.words : [];
        if (words.length === 0) continue;

        for (let wIdx = 0; wIdx < words.length; wIdx++) {
          const wObj = words[wIdx];
          const cleanWord = sanitizeWinAnsi(wObj.t);
          if (!cleanWord) continue;

          const textWithSpace = wIdx < words.length - 1 ? cleanWord + ' ' : cleanWord;

          // Transform word box if operator manually changed rotation relative to detectedRotation
          let wx = wObj.x;
          let wy = wObj.y;
          let ww = wObj.w;
          let wh = wObj.h;
          if (relRot === 90) {
            wx = baseImgH - (wObj.y + wObj.h);
            wy = wObj.x;
            ww = wObj.h;
            wh = wObj.w;
          } else if (relRot === 180) {
            wx = baseImgW - (wObj.x + wObj.w);
            wy = baseImgH - (wObj.y + wObj.h);
          } else if (relRot === 270) {
            wx = wObj.y;
            wy = baseImgW - (wObj.x + wObj.w);
            ww = wObj.h;
            wh = wObj.w;
          }

          // Convert to upright PDF space (rw x rh) then to final normalized [0, 0, stdW, stdH] space
          const xrWord = wx * scaleX;
          const yrWord = Math.max(0, rh - (wy + wh * 0.85) * scaleY);
          const wrWord = Math.max(1, ww * scaleX);
          const hrWord = Math.max(4, wh * scaleY);

          const targetX = xrWord * s + (destX - s * cropX);
          const targetY = yrWord * s + (destY - s * cropY);
          const targetW = Math.max(1, wrWord * s);
          const targetH = Math.max(4, hrWord * s);

          const fontSize = Math.max(4, Math.min(120, targetH));
          let measuredW = 0;
          try {
            measuredW = helveticaFont.widthOfTextAtSize(cleanWord, fontSize);
          } catch (_) {
            measuredW = cleanWord.length * fontSize * 0.5;
          }

          let horizScale = 100;
          if (measuredW > 0.5 && targetW > 0.5) {
            horizScale = Math.max(30, Math.min(300, (targetW / measuredW) * 100));
          }

          const escaped = escapePdfLiteralString(textWithSpace);
          suffixOps.push(
            `BT ${fontKeyStr} ${fontSize.toFixed(1)} Tf ${horizScale.toFixed(1)} Tz ${targetX.toFixed(2)} ${targetY.toFixed(2)} Td (${escaped}) Tj ET`
          );

          totalWordsEmbedded++;
          pageHasWords = true;
        }
      }

      suffixOps.push('Q');
      if (pageHasWords) {
        pagesWithText++;
      }
    }

    const suffixStream = pdfDoc.context.flateStream(suffixOps.join('\n') + '\n');
    const suffixRef = pdfDoc.context.register(suffixStream);
    page.node.addContentStream(suffixRef);

    // 5. Normalize all PDF page boxes to the exact same uniform size [0, 0, stdW, stdH] & rotation 0!
    page.setMediaBox(0, 0, stdW, stdH);
    page.setCropBox(0, 0, stdW, stdH);
    try {
      page.setTrimBox(0, 0, stdW, stdH);
      page.setBleedBox(0, 0, stdW, stdH);
    } catch (_) {}
    page.setRotation(degrees(0));

    if (onProgress && (i % 25 === 0 || i === pdfPages.length - 1)) {
      onProgress(i + 1, pdfPages.length);
    }
  }

  // 6. Delete pages marked as blank / deleted (in reverse order so indices stay valid)
  for (let i = pdfPages.length - 1; i >= 0; i--) {
    const pState = resolvedStates[i];
    if (pState && pState.deleted && pdfDoc.getPageCount() > 1) {
      pdfDoc.removePage(i);
    }
  }

  const outDir = path.dirname(outputPdfPath);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const finalPdfBytes = await pdfDoc.save({ useObjectStreams: false });
  let actualSavedPath = outputPdfPath;
  try {
    await fs.promises.writeFile(actualSavedPath, finalPdfBytes);
  } catch (writeErr) {
    if (writeErr.code === 'EBUSY' || writeErr.code === 'EPERM' || writeErr.code === 'EACCES') {
      const ext = path.extname(outputPdfPath);
      const base = path.basename(outputPdfPath, ext);
      let suffix = 1;
      while (true) {
        const altPath = path.join(outDir, `${base} (QC-${suffix})${ext}`);
        try {
          await fs.promises.writeFile(altPath, finalPdfBytes);
          actualSavedPath = altPath;
          break;
        } catch (_) {
          suffix++;
          if (suffix > 20) throw writeErr;
        }
      }
    } else {
      throw writeErr;
    }
  }

  return {
    actualSavedPath,
    uniformPageSize: `${stdW}x${stdH}`,
    originalPageCount: pdfPages.length,
    finalPageCount: pdfDoc.getPageCount(),
    deletedBlankCount,
    croppedPageCount,
    rotatedPageCount,
    pagesWithText,
    totalWordsEmbedded,
    outputSizeBytes: finalPdfBytes.length,
    pageStates: resolvedStates
  };
}

module.exports = {
  buildSearchablePdf,
  readOcrJsonl,
  writeOcrJsonl,
  createDefaultPageStates,
  sanitizeWinAnsi
};
